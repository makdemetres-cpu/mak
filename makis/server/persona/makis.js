export const SCENARIO_IDS = Object.keys(SCENARIOS);

export function pickScenario(requested) {
  if (requested && SCENARIOS[requested]) return SCENARIOS[requested];
  const ids = SCENARIO_IDS;
  return SCENARIOS[ids[Math.floor(Math.random() * ids.length)]];
}

export function pickupLine(scenario) {
  const lines = scenario.pickup;
  return lines[Math.floor(Math.random() * lines.length)];
}

