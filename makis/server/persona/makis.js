/** Compact transcript for the model: who said what, in order. */
export function toModelHistory(turns) {
  return turns.map((t) => ({
    role: t.speaker === 'user' ? 'user' : 'assistant',
    content: t.speaker === 'user' ? t.text : JSON.stringify({ say: t.text }),
  }));
}
